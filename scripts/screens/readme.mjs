import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const HEADER = `# Screens

Generated by \`node scripts/screens.mjs\`. Do not edit by hand. Rerun after a UI change and commit the PNGs.
Fake data only: every network call is stubbed. Light colour scheme, reduced motion, UTC clock.

`;

/** Lists every screenshot, sorted by file name, so reruns give the same text. */
export function writeReadme(dir, shots) {
  const rows = [...shots]
    .sort((a, b) => (a.file < b.file ? -1 : 1))
    .map((s) => `| [${s.file}](${s.file}) | ${s.shows} |`);
  const table = ['| File | Shows |', '| --- | --- |', ...rows];
  writeFileSync(join(dir, 'README.md'), `${HEADER}${table.join('\n')}\n`);
}
