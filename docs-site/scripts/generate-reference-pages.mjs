// Turns generated-source/reference.json (printed by the Rust relay) into markdown pages.
// The pages are regenerated on every build and never edited by hand.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { jsonBlock, propertyTable, resolve } from './schema-to-markdown.mjs';

const SOURCE = join(dirname(fileURLToPath(import.meta.url)), '..', 'generated-source');
const reference = JSON.parse(readFileSync(join(SOURCE, 'reference.json'), 'utf8'));
mkdirSync(join(SOURCE, 'reference'), { recursive: true });

const notice = (from) =>
  `<!-- Generated by docs-site/scripts/generate-reference-pages.mjs. Do not edit. -->\n\n::: info Generated page\nBuilt from \`${from}\` on every docs build, so it always matches the code.\n:::\n\n`;

function toolPage(tools) {
  const body = tools.map((tool) => {
    const { $schema, ...schema } = tool.inputSchema;
    return [
      `## \`${tool.name}\`\n`,
      `${tool.description}\n`,
      '### Parameters\n',
      propertyTable(schema, {}),
      '### Input schema\n',
      jsonBlock(schema),
    ].join('\n');
  });
  return `# MCP tool reference\n\n${notice('server/src/mcp_location_tool.rs')}${body.join('\n')}`;
}

function messageSection(title, schema) {
  const defs = schema.$defs ?? {};
  const rows = schema.oneOf.map((variant) => {
    const found = resolve(variant, defs);
    const name = found.properties.type.const;
    return `### \`${name}\`\n\n${found.description ?? ''}\n\n${propertyTable(found, defs, ['type'])}`;
  });
  return `## ${title}\n\n${schema.description}\n\nEvery message is a JSON object whose \`type\` field names the message.\n\n${rows.join('\n')}`;
}

function wirePage() {
  const sections = [
    messageSection('Relay to phone', reference.to_device),
    messageSection('Phone to relay', reference.from_device),
  ];
  return `# Wire messages\n\n${notice('server/src/relay_wire_protocol.rs')}${sections.join('\n')}`;
}

writeFileSync(join(SOURCE, 'reference', 'mcp-tools.md'), toolPage(reference.mcp_tools));
writeFileSync(join(SOURCE, 'reference', 'wire-messages.md'), wirePage());
console.log('Wrote reference/mcp-tools.md and reference/wire-messages.md');
